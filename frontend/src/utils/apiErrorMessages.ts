/** Mongoose wraps validator messages: "<Model> validation failed: <path>: <message>[, <path>: <message>]". */
const MONGOOSE_VALIDATION = /^\w+ validation failed: [\w.]+: (.+?)(?:, [\w.]+: .*)?$/

export const API_NETWORK_ERROR_KEY = 'apiErrors.network'
export const API_GENERIC_ERROR_KEY = 'apiErrors.generic'

/** Returns the i18n key (and interpolation params) for a known backend message, or null. */
export function apiErrorTranslation(message: string): ApiErrorTranslation | null {
  const text = message.trim()
  if (!text) return null
  if (Object.prototype.hasOwnProperty.call(API_ERROR_KEYS, text)) return { key: API_ERROR_KEYS[text] }
  for (const { pattern, key, params } of API_ERROR_PATTERNS) {
    const match = text.match(pattern)
    if (match) return { key, params: params(match) }
  }
  const inner = text.match(MONGOOSE_VALIDATION)?.[1]
  if (inner && inner !== text) return apiErrorTranslation(inner)
  return null
}
